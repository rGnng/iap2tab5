#!/usr/bin/env python3
"""Generate a deterministic, balanced 64x64 blue-noise texture for RGB565 finishing.

Void-and-cluster ranking runs only on the development machine. Firmware reads
the resulting 4 KB table; it never generates or animates noise at runtime.
"""
import math
from pathlib import Path
import random

SIDE = 64
COUNT = SIDE * SIDE
KERNEL = [(x, y, math.exp(-(x*x+y*y)/(2*1.5**2)))
          for y in range(-6, 7) for x in range(-6, 7)]


def change(density, index, amount):
    x, y = index % SIDE, index // SIDE
    for dx, dy, weight in KERNEL:
        density[((y+dy) % SIDE)*SIDE+(x+dx) % SIDE] += amount * weight


def density_of(points):
    density = [0.0] * COUNT
    for index in points:
        change(density, index, 1)
    return density


def main():
    points = set(random.Random(9371).sample(range(COUNT), COUNT//10))
    density = density_of(points)
    for _ in range(COUNT*4):
        cluster = max(sorted(points), key=density.__getitem__)
        points.remove(cluster)
        change(density, cluster, -1)
        void = min((i for i in range(COUNT) if i not in points), key=density.__getitem__)
        points.add(void)
        change(density, void, 1)
        if void == cluster:
            break
    else:
        raise RuntimeError('Noise relaxation did not converge')

    initial = points.copy()
    ranks = [0] * COUNT
    for rank in range(len(points)-1, -1, -1):
        cluster = max(sorted(points), key=density.__getitem__)
        ranks[cluster] = rank
        points.remove(cluster)
        change(density, cluster, -1)
    points = initial.copy()
    density = density_of(points)
    for rank in range(len(points), COUNT//2):
        void = min((i for i in range(COUNT) if i not in points), key=density.__getitem__)
        ranks[void] = rank
        points.add(void)
        change(density, void, 1)
    points = set(range(COUNT)) - points
    density = density_of(points)
    for rank in range(COUNT//2, COUNT):
        cluster = max(sorted(points), key=density.__getitem__)
        ranks[cluster] = rank
        points.remove(cluster)
        change(density, cluster, -1)

    levels = [rank*16//COUNT for rank in ranks]
    assert all(levels.count(level) == COUNT//16 for level in range(16))
    rows = ['    {' + ','.join(f'{v:2}' for v in levels[y*SIDE:(y+1)*SIDE]) + '},'
            for y in range(SIDE)]
    destination = Path(__file__).resolve().parents[1]/'app/backend/cover_gradient_noise.h'
    destination.write_text('''/* Generated by tools/generate_gradient_noise.py; do not edit by hand. */
#ifndef IAP2TAB5_COVER_GRADIENT_NOISE_H
#define IAP2TAB5_COVER_GRADIENT_NOISE_H

static const uint8_t cover_gradient_noise[64][64] = {
''' + '\n'.join(rows) + '\n};\n\n#endif\n')
    print(f'Generated {destination}: 4096 samples, 16 balanced levels')


if __name__ == '__main__':
    main()
