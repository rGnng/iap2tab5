#!/usr/bin/env python3
"""Rasterize the vendored notification SVGs as recolorable LVGL A8 images.

Requires CairoSVG 2.8.2 and Pillow 12.0.0. No network access is needed.
"""
from io import BytesIO
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 32


def main():
    out = ['/* Generated by tools/gen_notification_icons.py. See assets/icons/README.md. */',
           '#ifndef IAP2TAB5_NOTIFICATION_ICONS_H',
           '#define IAP2TAB5_NOTIFICATION_ICONS_H', '#include "lvgl.h"', '']
    for name in ('arrow-repeat', 'bluetooth-x', 'bluetooth-connecting',
                 'battery-charging', 'plug', 'battery-full', 'battery-low'):
        png = cairosvg.svg2png(url=str(ROOT / 'assets/icons' / (name + '.svg')),
                              output_width=SIZE, output_height=SIZE)
        alpha = Image.open(BytesIO(png)).convert('RGBA').getchannel('A').tobytes()
        symbol = 'notification_' + name.replace('-', '_')
        out.append(f'static const uint8_t {symbol}_data[] = {{')
        out.extend('    ' + ', '.join(f'0x{x:02x}' for x in alpha[i:i+20]) + ','
                   for i in range(0, len(alpha), 20))
        out.extend(['};', f'static const lv_image_dsc_t {symbol} = {{',
                    '    .header.magic = LV_IMAGE_HEADER_MAGIC,',
                    '    .header.cf = LV_COLOR_FORMAT_A8,',
                    f'    .header.w = {SIZE}, .header.h = {SIZE}, .header.stride = {SIZE},',
                    f'    .data_size = sizeof({symbol}_data), .data = {symbol}_data,',
                    '};', ''])
    out.append('#endif /* IAP2TAB5_NOTIFICATION_ICONS_H */')
    (ROOT / 'app/ui/notification_icons.h').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
