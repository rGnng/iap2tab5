#!/usr/bin/env python3
"""Embed assets/web/ into firmware/main/web_index.h.

The device serves the page from flash, so the HTML is compiled in.  Edit the
HTML/CSS/JS sources, run this script, and rebuild the firmware.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = {"INDEX_HTML": "index.html", "DEBUG_HTML": "debug.html",
          "WEB_STYLE_CSS": "style.css", "WEB_COMMON_JS": "common.js",
          "WEB_DASHBOARD_JS": "dashboard.js", "WEB_DEBUG_JS": "debug.js"}
OUT = ROOT / "firmware/main/web_index.h"


def c_string(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
        )
        out.append(f'"{escaped}"\n')
    return "".join(out)


def main() -> int:
    assets = [(name, (ROOT / "assets/web" / filename).read_text(encoding="utf-8"))
              for name, filename in ASSETS.items()]
    body = (
        "/* Generated by tools/gen_web_ui.py from assets/web/.\n"
        " * Do not edit by hand. */\n"
        "#ifndef IAP2TAB5_WEB_INDEX_H\n"
        "#define IAP2TAB5_WEB_INDEX_H\n\n"
        + "".join(f"static const char {name}[] =\n{c_string(text)};\n\n" for name, text in assets)
        + "#endif /* IAP2TAB5_WEB_INDEX_H */\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(len(text.encode()) for _, text in assets)} bytes of web assets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
