#!/usr/bin/env python3
"""Embed assets/web/index.html into firmware/main/web_index.h.

The device serves the page from flash, so the HTML is compiled in.  Edit the
HTML source, run this script, and rebuild the firmware.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets/web/index.html"
OUT = ROOT / "firmware/main/web_index.h"


def c_string(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
        )
        out.append(f'"{escaped}"\n')
    return "".join(out)


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    body = (
        "/* Generated by tools/gen_web_ui.py from assets/web/index.html.\n"
        " * Do not edit by hand. */\n"
        "#ifndef IAP2TAB5_WEB_INDEX_H\n"
        "#define IAP2TAB5_WEB_INDEX_H\n\n"
        "static const char INDEX_HTML[] =\n"
        f"{c_string(text)};\n\n"
        "#endif /* IAP2TAB5_WEB_INDEX_H */\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes of HTML)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
